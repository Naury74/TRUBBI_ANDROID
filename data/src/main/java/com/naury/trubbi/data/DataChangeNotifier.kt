package com.naury.trubbi.data

/**
 * 저장된 내용이 바뀌었을 때 앱 밖 표면에 알린다.
 *
 * 바탕화면 위젯은 앱이 떠 있지 않아도 데이터를 보여 주므로, 저장이 끝난 시점에 누군가
 * 다시 그리라고 알려 줘야 한다. 그 일을 리포지토리가 위젯 클래스를 직접 부르며 하면
 * 데이터 계층이 화면 구성 요소를 알게 된다.
 *
 * 그래서 리포지토리는 "무엇이 바뀌었는지"만 이 인터페이스로 알리고, 그 알림을 무엇으로
 * 옮길지는 구현이 정한다. 위젯이 없는 빌드나 테스트에서는 아무 일도 하지 않는 구현을 끼우면 된다.
 */
interface DataChangeNotifier {

    /** 바코드 기록이 추가·수정·삭제됐다. */
    fun barcodesChanged()

    /** 진행 중 여정의 정차지·단계·위치가 바뀌었다. */
    fun journeyChanged()
}
